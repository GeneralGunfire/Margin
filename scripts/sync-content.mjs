// Reads /content and writes supabase/content-sync.sql (topics + lessons index upserts).
// Paste that file into the Supabase SQL editor after adding or renaming lessons.
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join } from "node:path";

const root = "content";
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

function fm(raw) {
  const m = raw.replace(/\r\n/g, "\n").match(/^---\n([\s\S]*?)\n---/);
  const d = {};
  if (m) for (const line of m[1].split("\n")) {
    const kv = line.match(/^([A-Za-z_]+):\s*(.*)$/);
    if (kv) d[kv[1]] = kv[2].trim().replace(/^["']|["']$/g, "");
  }
  return d;
}

const topics = new Map();
const lessons = [];
for (const subj of readdirSync(root)) {
  if (!statSync(join(root, subj)).isDirectory()) continue;
  for (const topic of readdirSync(join(root, subj))) {
    if (!statSync(join(root, subj, topic)).isDirectory()) continue;
    for (const file of readdirSync(join(root, subj, topic)).filter((f) => f.endsWith(".md"))) {
      const d = fm(readFileSync(join(root, subj, topic, file), "utf8"));
      const slug = file.replace(/\.md$/, "");
      const tid = `${subj}/${topic}`;
      if (!topics.has(tid)) topics.set(tid, { subj: d.subject || subj, title: d.topic || topic.replace(/-/g, " "), part: d.part || null });
      lessons.push({ id: `${tid}/${slug}`, tid, title: d.title || slug, sort: Number(d.order || 0) });
    }
  }
}

let sql = "-- Generated by `npm run sync-content`. Paste into the Supabase SQL editor.\n";
let i = 0;
for (const [id, t] of topics) {
  sql += `insert into public.topics (id, subject_id, title, part, sort) values (${q(id)}, (select id from public.subjects where slug = ${q(t.subj)}), ${q(t.title)}, ${t.part ? q(t.part) : "null"}, ${i++})\n  on conflict (id) do update set subject_id = excluded.subject_id, title = excluded.title, part = excluded.part, sort = excluded.sort;\n`;
}
for (const l of lessons) {
  sql += `insert into public.lessons (id, topic_id, title, sort) values (${q(l.id)}, ${q(l.tid)}, ${q(l.title)}, ${l.sort})\n  on conflict (id) do update set topic_id = excluded.topic_id, title = excluded.title, sort = excluded.sort;\n`;
}
writeFileSync("supabase/content-sync.sql", sql);
console.log(`Wrote supabase/content-sync.sql (${topics.size} topics, ${lessons.length} lessons)`);
